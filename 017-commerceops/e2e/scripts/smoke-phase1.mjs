import { chromium } from '@playwright/test';
const out = process.env.OUT;
const U = Date.now().toString(36).slice(-4).toUpperCase();
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1366, height: 860 } });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push('PAGEERROR ' + e.message));
await page.goto('http://localhost:3000/login');
await page.fill('#email', 'owner@demo.test');
await page.fill('#password', 'Demo-Owner-2026');
await page.click('button[type=submit]');
await page.waitForURL('http://localhost:3000/');
await page.screenshot({ path: `${out}/01-home.png` });
await page.goto('http://localhost:3000/settings/warehouses');
await page.getByRole('button', { name: '倉庫を追加' }).click();
await page.fill('#wh-code', 'W' + U);
await page.fill('#wh-name', '東京倉庫');
await page.getByRole('button', { name: '保存' }).click();
await page.waitForTimeout(800);
await page.fill('#loc-bulk', `A-${U}-1,A\nA-${U}-2,A`);
await page.getByRole('button', { name: '追加', exact: true }).click();
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/02-warehouses.png`, fullPage: true });
await page.goto('http://localhost:3000/settings/channels');
await page.getByRole('button', { name: 'チャネルを追加' }).click();
await page.fill('#ch-name', 'Web Store');
await page.fill('#ch-code', 'C' + U);
await page.getByRole('button', { name: '保存' }).click();
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/03-channels.png` });
await page.goto('http://localhost:3000/settings/import-profiles/new');
await page.waitForSelector('#pf-name');
await page.screenshot({ path: `${out}/04-profile-editor.png`, fullPage: true });
await page.goto('http://localhost:3000/settings/users');
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/05-users.png` });
await page.goto('http://localhost:3000/inventory/products');
await page.getByRole('button', { name: '商品を追加' }).click();
await page.fill('#pm-sku', 'SKU-' + U);
await page.fill('#pm-name', 'オーガニックTシャツ');
await page.fill('#pm-var', 'Red / M');

await page.getByRole('button', { name: '保存' }).click();
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/06-products.png` });
// mobile viewport of settings
const m = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
await m.context().addCookies(await page.context().cookies());
await m.goto('http://localhost:3000/settings/organization');
await m.waitForTimeout(800);
await m.screenshot({ path: `${out}/07-mobile-settings.png` });
console.log('errors:', JSON.stringify(errors));
await browser.close();
